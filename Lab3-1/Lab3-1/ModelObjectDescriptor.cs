using Silk.NET.OpenGL;
using System;

namespace Labor3_1
{
    internal class ModelObjectDescriptor : IDisposable
    {
        private bool disposedValue;

        public uint Vao { get; private set; }
        public uint Vertices { get; private set; }
        public uint Colors { get; private set; }
        public uint Indices { get; private set; }
        public uint IndexArrayLength { get; private set; }

        private GL Gl;

        /// <summary>
        /// Egy függőleges deszka (téglalap) az X-Y síkban, az origó köré központosítva,
        /// a "külső" oldala a +Z irányba néz (CCW = elölnézet).
        /// </summary>
        /// <param name="width">szélesség (X)</param>
        /// <param name="height">magasság (Y)</param>
        /// <param name="smoothNormals">
        /// false: minden csúcs normálisa (0,0,1), merőleges a lap síkjára.
        /// true: a bal oldali csúcsok normálisa -halfAngle-lel, a jobb oldaliaké +halfAngle-lel
        /// van elforgatva az Y tengely körül, vagyis a lap közepétől kifelé fordulnak.
        /// </param>
        /// <param name="halfAngle">a szomszédos lapok közti szög fele radiánban (itt 10 fok)</param>
        public static ModelObjectDescriptor CreatePlank(GL Gl, float width, float height, bool smoothNormals, float halfAngle)
        {
            float hw = width / 2f;
            float hh = height / 2f;

            float nxSide = smoothNormals ? MathF.Sin(halfAngle) : 0f;
            float nz = smoothNormals ? MathF.Cos(halfAngle) : 1f;

            // pozíció (3) + normális (3), CCW sorrend a +Z felől nézve
            float[] vertexArray = new float[] {
                -hw, -hh, 0f, -nxSide, 0f, nz,   // bal alsó
                 hw, -hh, 0f,  nxSide, 0f, nz,   // jobb alsó
                 hw,  hh, 0f,  nxSide, 0f, nz,   // jobb felső
                -hw,  hh, 0f, -nxSide, 0f, nz,   // bal felső
            };

            // barna "fa" szín
            float[] colorArray = new float[] {
                0.65f, 0.42f, 0.20f, 1f,
                0.65f, 0.42f, 0.20f, 1f,
                0.65f, 0.42f, 0.20f, 1f,
                0.65f, 0.42f, 0.20f, 1f,
            };

            uint[] indexArray = new uint[] {
                0, 1, 2,
                0, 2, 3
            };

            return Build(Gl, vertexArray, colorArray, indexArray);
        }

